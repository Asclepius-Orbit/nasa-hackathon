"""Fake wearable Arduino: speaks the line protocol over TCP, to test the gateway without the board.

The real gateway reads a pyserial serial port; with ``socket://host:port`` that port is a TCP connection, and the emulator is
the server on the other side. Use with the gateway (two terminals, with a Mosquitto on 127.0.0.1:1883)::

    uv run spine-arduino-emulator --port 5000
    SPINE_GATEWAY_SERIAL_URL=socket://127.0.0.1:5000 uv run spine-gateway

Failure options: ``--no-imu`` (like the firmware without MPU-6050), ``--drop-every N`` (every N-th batch is not sent but spends its
``frame_seq``, like an overrun) and ``--reboot-after S`` (device reboot S seconds after power-on). In Docker, the
``gateway-demo`` profile of ``app/docker-compose.yml`` starts emulator and gateway together.

Two layers:

- ``EmulatedArduino``: pure core, without sockets or wall clock. Given the device time it returns the due lines,
  always with ``protocol.encode_*`` (the format is defined by ``protocol``, not this module). Like the real firmware, it repeats the hello
  next to each tick: pyserial ``socket://`` flushes the input buffer right when opening the port (just like an Uno, which
  resets on open), so it can never be assumed that the first hello arrives; a repeated hello with the same ``boot_id`` is
  harmless to the gateway.
- ``serve``: asyncio server that handles one client at a time and gives it a new device (like an Arduino reset by DTR:
  new ``boot_id``, sequences and ``millis`` at zero). Paces itself with an injectable ``sleep``.

The signals are synthetic and deterministic (a function of the seed and of the device time), but not trivial: they are generated by
``spine_physiology`` (``spine_gateway.signals``) and come out as raw firmware counts (10-bit EMG, MPU-6050 int16 IMU
at ±4 g and ±500 dps, cord through the 10 kΩ divider). There is one flexion repetition of 3 s every 4 s (what the backend counts in
gyro_x), with the EMG contraction and the cord stretch coupled to the same phase of the effort; noise, bias and hysteresis
come from the ``physiology`` models.
"""

import argparse
import asyncio
import contextlib
import logging
import math
import random
import signal
import sys
import time
from collections.abc import Awaitable, Callable, Coroutine, Sequence
from typing import Any

from spine_gateway.protocol import (
    PROTOCOL_VERSION,
    SEQ_MODULUS,
    U16_MAX,
    U32_MAX,
    Frame,
    FrameKind,
    Hello,
    ImuSample,
    Tick,
    encode_frame,
    encode_hello,
    encode_tick,
)
from spine_gateway.signals import EmulatedSignals

_log = logging.getLogger(__name__)

FIRMWARE_VERSION = "0.1.0-emu"
STEP_MS = 100
"""Period of the ``D`` batches (all three kinds go out together, like the firmware)."""
TICK_MS = 1000
"""Tick period (and of the repeated hello)."""

BOOT_ID_MULTIPLIER = 1664525
BOOT_ID_INCREMENT = 1013904223
"""Numerical Recipes linear congruential modulo 2^32: since the increment is odd and ``a - 1`` even, it never has a fixed point."""

IMU_ABSENT = "#imu absent"
DEFAULT_HOST = "127.0.0.1"
DEFAULT_PORT = 5000
LOG_FORMAT = "%(asctime)s %(levelname)s %(name)s: %(message)s"

# CLI texts as module constants: mutmut does not mutate the module and a wording change is not a behaviour change.
PROG = "spine-arduino-emulator"
DESCRIPTION = "Fake wearable Arduino over TCP (for SPINE_GATEWAY_SERIAL_URL=socket://host:port)"
HELP_HOST = "listening interface (0.0.0.0 in Docker)"
HELP_PORT = "TCP port (default %(default)s)"
HELP_SEED = "seed of the signals and of the boot_id"
HELP_NO_IMU = "like the firmware without MPU-6050: no I frames and with '#imu absent'"
HELP_DROP_EVERY = "every N-th batch is not emitted but spends its frame_seq (0: none)"
HELP_REBOOT_AFTER = "reboots the device S seconds after power-on"


def initial_boot_id(seed: int) -> int:
    """``boot_id`` of the first boot, derived from the seed (another generator: it does not alter the signals)."""
    return random.Random(f"boot-id:{seed}").getrandbits(32)


def next_boot_id(boot_id: int) -> int:
    """``boot_id`` of the next boot; always different from the current one."""
    return (boot_id * BOOT_ID_MULTIPLIER + BOOT_ID_INCREMENT) & U32_MAX


class EmulatedArduino:
    """Fake device: ``lines_until(device_ms)`` gives the lines (without ``\\n``) it has emitted up to that instant.

    ``device_ms`` is the milliseconds since power-on and must keep growing; the device advances in 100 ms steps and whatever
    has not completed a whole step is not emitted yet. The first call emits the hello (and ``#imu absent`` if there is no IMU).
    ``reboot_after_s`` reboots the device once, S seconds after boot: new ``boot_id`` (``next_boot_id``),
    sequences and ``millis`` at zero, and the batch of that step is lost. ``start_seq`` is the first ``frame_seq`` of each kind
    (useful to test the u16 wrap without 6,500 s of signal).
    """

    def __init__(
        self,
        seed: int = 0,
        *,
        boot_id: int | None = None,
        imu_present: bool = True,
        drop_every: int = 0,
        reboot_after_s: float | None = None,
        start_seq: int = 0,
    ) -> None:
        if drop_every < 0:
            raise ValueError(f"drop_every must be >= 0: {drop_every}")
        if reboot_after_s is not None and reboot_after_s <= 0:
            raise ValueError(f"reboot_after_s must be > 0: {reboot_after_s}")
        if boot_id is not None and not 0 <= boot_id <= U32_MAX:
            raise ValueError(f"boot_id must fit u32: {boot_id}")
        if not 0 <= start_seq <= U16_MAX:
            raise ValueError(f"start_seq must fit u16: {start_seq}")
        self._seed = seed
        self._signals = EmulatedSignals(seed)
        self._boot_id = initial_boot_id(seed) if boot_id is None else boot_id
        self._imu_present = imu_present
        self._drop_every = drop_every
        self._reboot_after_ms = None if reboot_after_s is None else reboot_after_s * 1000
        self._start_seq = start_seq
        self._power_ms = 0  # time processed since power-on (multiple of STEP_MS)
        self._boot_ms = 0  # the ``millis()`` of the current boot
        self._rebooted = False
        self._hello_due = True
        self._seq = dict.fromkeys(FrameKind, start_seq)
        self._batches = dict.fromkeys(FrameKind, 0)

    @property
    def boot_id(self) -> int:
        return self._boot_id

    @property
    def millis(self) -> int:
        """``millis()`` of the device at the last processed step."""
        return self._boot_ms

    def lines_until(self, device_ms: int) -> list[str]:
        """Lines due up to ``device_ms`` (since power-on), in the order in which the firmware would emit them."""
        out: list[str] = []
        if self._hello_due:
            out += self._boot_lines()
        while self._power_ms + STEP_MS <= device_ms:
            out += self._step()
        return out

    def _boot_lines(self) -> list[str]:
        self._hello_due = False
        lines = [self._hello()]
        if not self._imu_present:
            lines.append(IMU_ABSENT)
        return lines

    def _hello(self) -> str:
        return encode_hello(Hello(PROTOCOL_VERSION, self._boot_id, FIRMWARE_VERSION, self._boot_ms))

    def _step(self) -> list[str]:
        self._power_ms += STEP_MS
        self._boot_ms += STEP_MS
        if self._reboot_due():
            self._reboot()
            return self._boot_lines()
        lines: list[str] = []
        if self._boot_ms % TICK_MS == 0:
            lines += [self._hello(), encode_tick(Tick(self._boot_id, self._boot_ms))]
        t0 = self._boot_ms - STEP_MS
        lines += self._emit(FrameKind.EMG, t0, self._signals.emg(t0))
        if self._imu_present:
            lines += self._emit(FrameKind.IMU, t0, self._signals.imu(t0))
        lines += self._emit(FrameKind.CORD, t0, self._signals.cord(t0))
        return lines

    def _reboot_due(self) -> bool:
        return self._reboot_after_ms is not None and not self._rebooted and self._boot_ms >= self._reboot_after_ms

    def _reboot(self) -> None:
        self._rebooted = True
        self._boot_id = next_boot_id(self._boot_id)
        self._boot_ms = 0
        self._signals = EmulatedSignals(self._seed)  # the rebooted device starts its signal over
        self._seq = dict.fromkeys(FrameKind, self._start_seq)
        self._batches = dict.fromkeys(FrameKind, 0)
        self._hello_due = True

    def _emit(self, kind: FrameKind, t0: int, samples: tuple[int, ...] | tuple[ImuSample, ...]) -> list[str]:
        """The batch as a line, or nothing if the overrun hits it: in both cases it spends its ``frame_seq``."""
        seq = self._seq[kind]
        self._seq[kind] = (seq + 1) % SEQ_MODULUS
        self._batches[kind] += 1
        if self._drop_every and self._batches[kind] % self._drop_every == 0:
            return []
        return [encode_frame(Frame(kind, seq, t0, samples))]


# --- TCP server ---

type Sleep = Callable[[float], Awaitable[object]]


async def _serve_client(writer: asyncio.StreamWriter, device: EmulatedArduino, sleep: Sleep, clock: Callable[[], float]) -> None:
    """Emits the device at a 100 ms pace until the client leaves. Device time is ``step * 100 ms``; the clock
    only adjusts the wait (if a ``sleep`` takes too long, the following steps go out without waiting and no delay accumulates)."""
    start = clock()
    step = 0
    try:
        while True:
            writer.write("".join(f"{line}\n" for line in device.lines_until(step * STEP_MS)).encode("ascii"))
            await writer.drain()
            step += 1
            await sleep(max(0.0, start + step * STEP_MS / 1000 - clock()))
    except OSError:
        _log.info("client gone")  # the client closed (the gateway retries): the next one will see a rebooted device
    finally:
        writer.close()
        with contextlib.suppress(OSError):
            await writer.wait_closed()


async def serve(
    host: str,
    port: int,
    *,
    seed: int = 0,
    imu_present: bool = True,
    drop_every: int = 0,
    reboot_after_s: float | None = None,
    sleep: Sleep = asyncio.sleep,
    clock: Callable[[], float] = time.monotonic,
    on_listening: Callable[[int], None] | None = None,
) -> None:
    """Listens on ``host:port`` and handles one client at a time until cancelled.

    Each client receives a new device; the ``boot_id`` of each one follows the last of the previous (``next_boot_id``).
    ``on_listening`` receives the real port (useful with ``port=0``). On cancel the current client and the port are closed.
    """

    def new_device(boot_id: int | None) -> EmulatedArduino:
        return EmulatedArduino(seed, boot_id=boot_id, imu_present=imu_present, drop_every=drop_every, reboot_after_s=reboot_after_s)

    boot_id = new_device(None).boot_id  # a test device: invalid options fail now, not with the first client
    free = asyncio.Lock()  # one client at a time: the others wait in the backlog until the port is free
    handlers: set[asyncio.Task[None]] = set()

    async def handle(_: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
        nonlocal boot_id
        task = asyncio.current_task()
        assert task is not None
        handlers.add(task)
        try:
            async with free:
                device = new_device(boot_id)
                try:
                    await _serve_client(writer, device, sleep, clock)
                finally:
                    boot_id = next_boot_id(device.boot_id)
        finally:
            handlers.discard(task)

    server = await asyncio.start_server(handle, host, port)
    try:
        if on_listening is not None:
            on_listening(server.sockets[0].getsockname()[1])
        _log.info("Arduino emulator listening on %s:%d", host, server.sockets[0].getsockname()[1])
        await server.serve_forever()
    finally:
        server.close()
        for task in list(handlers):
            task.cancel()
        await asyncio.gather(*handlers, return_exceptions=True)
        await server.wait_closed()


# --- CLI ---


def _bounded(minimum: float, kind: type[int] | type[float], maximum: float = math.inf) -> Callable[[str], Any]:
    """argparse type: number of ``kind`` within ``[minimum, maximum]``."""

    def parse(text: str) -> Any:
        try:
            value = kind(text)
        except ValueError:
            raise argparse.ArgumentTypeError(f"not a number: {text!r}") from None
        if not minimum <= value <= maximum:
            raise argparse.ArgumentTypeError(f"must be between {minimum} and {maximum}: {text}")
        return value

    return parse


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(prog=PROG, description=DESCRIPTION)
    parser.add_argument("--host", default=DEFAULT_HOST, help=HELP_HOST)
    parser.add_argument("--port", type=_bounded(1, int, 65535), default=DEFAULT_PORT, help=HELP_PORT)
    parser.add_argument("--seed", type=int, default=0, help=HELP_SEED)
    parser.add_argument("--no-imu", action="store_true", help=HELP_NO_IMU)
    parser.add_argument("--drop-every", type=_bounded(0, int), default=0, help=HELP_DROP_EVERY)
    parser.add_argument("--reboot-after", type=_bounded(1e-9, float), default=None, help=HELP_REBOOT_AFTER)
    return parser.parse_args(argv)


async def run_until_stopped(run: Callable[..., Coroutine[Any, Any, None]], **options: Any) -> None:
    """``run`` until it finishes or is cancelled; SIGTERM (``docker stop``) counts as a requested stop, not an error."""
    task = asyncio.create_task(run(**options))
    loop = asyncio.get_running_loop()
    with contextlib.suppress(NotImplementedError, RuntimeError, AttributeError):  # Windows has no SIGTERM in the loop
        loop.add_signal_handler(signal.SIGTERM, task.cancel)
    try:
        await task
    except asyncio.CancelledError:
        current = asyncio.current_task()
        if current is not None and current.cancelling():
            raise
        _log.info("emulator stopped (SIGTERM)")
    finally:
        with contextlib.suppress(NotImplementedError, RuntimeError, AttributeError):
            loop.remove_signal_handler(signal.SIGTERM)


def main(argv: Sequence[str] | None = None, *, run: Callable[..., Coroutine[Any, Any, None]] = serve) -> None:
    """``uv run spine-arduino-emulator``: see the options with ``--help``."""
    logging.basicConfig(level=logging.INFO, format=LOG_FORMAT)
    args = parse_args(argv)
    options: dict[str, Any] = {
        "host": args.host,
        "port": args.port,
        "seed": args.seed,
        "imu_present": not args.no_imu,
        "drop_every": args.drop_every,
        "reboot_after_s": args.reboot_after,
    }
    loop_factory = asyncio.SelectorEventLoop if sys.platform == "win32" else None
    try:
        asyncio.run(run_until_stopped(run, **options), loop_factory=loop_factory)
    except KeyboardInterrupt:
        pass  # Ctrl+C: ``serve`` already closed the client and the port when cancelled


if __name__ == "__main__":
    main()
